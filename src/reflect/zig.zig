//! A shader tree as one Zig source: every program's texts, its reflection as tables, and
//! each uniform block as an `extern struct` laid out by std140 (offsets checked at compile
//! time). The file imports only `std`: a host that uses it links no compiler.

const std = @import("std");
const Session = @import("../Session.zig");
const Ir = @import("../ir/Ir.zig");
const emit = @import("../emit/emit.zig");
const types = @import("../sema/types.zig");
const R = @import("Reflection.zig");
const version = @import("../bulg.zig").version;
const Type = types.Type;

pub const Error = error{ OutOfMemory, NotChecked, Unsupported };

pub const Options = struct {
    /// the dialects whose texts are in the file (each program gets a field per dialect)
    dialects: []const emit.Dialect = &.{ .es300, .glsl330 },
};

/// The Zig source for every program of the session that checks (all must: a program
/// that does not is `error.NotChecked`).
pub fn generate(s: *const Session, options: Options, out: std.mem.Allocator) Error![]u8 {
    var arena_state: std.heap.ArenaAllocator = .init(out);
    defer arena_state.deinit();
    const a = arena_state.allocator();
    var g: Gen = .{ .s = s, .a = a, .text = .init(out), .options = options };
    errdefer g.text.deinit();
    try g.run();
    return g.text.toOwnedSlice();
}

const Gen = struct {
    s: *const Session,
    a: std.mem.Allocator,
    text: std.Io.Writer.Allocating,
    options: Options,
    /// the blocks written so far, by their module and name
    blocks: std.ArrayList(struct { []const u8, []const u8 }) = .empty,

    fn w(g: *Gen) *std.Io.Writer {
        return &g.text.writer;
    }
    fn put(g: *Gen, bytes: []const u8) Error!void {
        g.w().writeAll(bytes) catch return error.OutOfMemory;
    }
    fn print(g: *Gen, comptime fmt: []const u8, values: anytype) Error!void {
        g.w().print(fmt, values) catch return error.OutOfMemory;
    }

    fn run(g: *Gen) Error!void {
        try g.print(
            \\//! Generated by BULG {f} from {d} sources: change the sources, not this file.
            \\
            \\const std = @import("std");
            \\
            \\
        , .{ version, g.s.sources.items.len });
        try g.put(prelude);
        try g.dialectEnum();

        var programs: std.ArrayList(*const Ir.Program) = .empty;
        var refl: std.ArrayList(R.Reflection) = .empty;
        for (g.s.programs) |*p| {
            if (p.is_template) continue;
            try programs.append(g.a, p);
            try refl.append(g.a, try R.reflect(g.s, p, g.a));
        }

        // the blocks, once each
        try g.put("\n/// The uniform blocks, laid out by std140 (an `extern struct` per block).\npub const blocks = struct {\n");
        for (refl.items) |r| for (r.blocks) |b| try g.block(b);
        try g.put("};\n");

        // the programs
        try g.put("\n/// Every program.\npub const Program = enum {\n");
        for (programs.items) |p| try g.print("    {f},\n", .{std.zig.fmtId(p.name)});
        try g.put("};\n");
        for (programs.items, refl.items) |p, r| try g.program(p, r);

        // one table, for code that takes a `Program` at run time
        try g.put("\n/// Each program's description, by `Program`.\npub const programs = std.EnumArray(Program, Info).init(.{\n");
        for (programs.items) |p| try g.print("    .{f} = {f}.info,\n", .{ std.zig.fmtId(p.name), std.zig.fmtId(p.name) });
        try g.put("});\n");
    }

    fn dialectEnum(g: *Gen) Error!void {
        try g.put("\n/// The dialects this file has texts in.\npub const Dialect = enum {");
        for (g.options.dialects, 0..) |d, i| try g.print("{s} {t}", .{ if (i == 0) "" else ",", d });
        try g.put(" };\n\n/// A stage's text in each dialect.\npub const Texts = std.EnumArray(Dialect, []const u8);\n");
    }

    fn block(g: *Gen, b: R.Block) Error!void {
        for (g.blocks.items) |x| if (std.mem.eql(u8, x[0], b.module) and std.mem.eql(u8, x[1], b.name)) return;
        try g.blocks.append(g.a, .{ b.module, b.name });
        try g.print("    /// `{s}`, from {s} ({d} bytes)\n    pub const {f} = extern struct {{\n", .{ b.name, b.module, b.size, std.zig.fmtId(b.name) });
        var off: u32 = 0;
        var pad: u32 = 0;
        for (b.members) |m| {
            if (m.offset > off) {
                try g.print("        _pad{d}: [{d}]u8 = @splat(0),\n", .{ pad, m.offset - off });
                pad += 1;
            }
            try g.print("        {f}: ", .{std.zig.fmtId(m.name)});
            try g.zigType(m.type);
            try g.put(" = ");
            if (m.default) |d| {
                try g.zigValue(m.type, d);
            } else {
                try g.put("std.mem.zeroes(");
                try g.zigType(m.type);
                try g.put(")");
            }
            try g.put(",\n");
            off = m.offset + m.size;
        }
        if (b.size > off) try g.print("        _pad{d}: [{d}]u8 = @splat(0),\n", .{ pad, b.size - off });
        try g.print("\n        comptime {{\n            std.debug.assert(@sizeOf(@This()) == {d});\n", .{b.size});
        for (b.members) |m| try g.print("            std.debug.assert(@offsetOf(@This(), \"{s}\") == {d});\n", .{ m.name, m.offset });
        try g.put("        }\n    };\n");
    }

    /// The Zig type of a std140 member.
    fn zigType(g: *Gen, t: Type) Error!void {
        const pool = &g.s.pool;
        if (pool.arrayOf(t)) |a| {
            // std140 rounds every element up to 16 bytes
            try g.print("[{d}]", .{a.len});
            if (a.elem.matrixLen() != null or a.elem.vectorLen() == 4 or pool.structOf(a.elem) != null) return g.zigType(a.elem);
            if (a.elem.scalarOf()) |s| return g.print("[4]{s}", .{scalarZig(s)});
            return g.zigType(a.elem);
        }
        if (pool.structOf(t)) |st| {
            // a struct in a block: its own std140 layout, written in place
            try g.put("extern struct {");
            var off: u32 = 0;
            var pad: u32 = 0;
            for (st.fields) |f| {
                const l = types.std140(pool, f.type);
                const at = std.mem.alignForward(u32, off, l.alignment);
                if (at > off) {
                    try g.print(" _pad{d}: [{d}]u8 = @splat(0),", .{ pad, at - off });
                    pad += 1;
                }
                try g.print(" {f}: ", .{std.zig.fmtId(f.name)});
                try g.zigType(f.type);
                try g.put(" = std.mem.zeroes(");
                try g.zigType(f.type);
                try g.put("),");
                off = at + l.size;
            }
            const size = types.std140(pool, t).size;
            if (size > off) try g.print(" _pad{d}: [{d}]u8 = @splat(0),", .{ pad, size - off });
            return g.put(" }");
        }
        const s = t.scalarOf() orelse return g.put("u32");
        if (t.matrixLen()) |n| return g.print("[{d}][4]{s}", .{ n, scalarZig(s) });
        const n = t.vectorLen().?;
        if (n == 1) return g.put(scalarZig(s));
        try g.print("[{d}]{s}", .{ n, scalarZig(s) });
    }

    /// A member's default, as a literal of its std140 type (`value` has its components).
    fn zigValue(g: *Gen, t: Type, value: []const Ir.Const) Error!void {
        if (t.matrixLen()) |n| {
            // columns, each padded to four
            try g.put(".{");
            for (0..n) |c| {
                try g.put(if (c == 0) " .{ " else ", .{ ");
                for (0..4) |row| {
                    if (row > 0) try g.put(", ");
                    if (row < n) try g.number(value[c * n + row]) else try g.put("0");
                }
                try g.put(" }");
            }
            return g.put(" }");
        }
        if (value.len == 1) return g.number(value[0]);
        try g.put(".{ ");
        for (value, 0..) |v, i| {
            if (i > 0) try g.put(", ");
            try g.number(v);
        }
        try g.put(" }");
    }

    fn program(g: *Gen, p: *const Ir.Program, r: R.Reflection) Error!void {
        try g.print("\npub const {f} = struct {{\n", .{std.zig.fmtId(p.name)});
        for ([_]Ir.Stage{ .vertex, .fragment }) |stage| {
            try g.print("    pub const {s}: Texts = .init(.{{\n", .{@tagName(stage)});
            for (g.options.dialects) |d| {
                var e = try emit.emit(g.s, p, stage, d, g.a);
                try g.print("        .{t} =\n", .{d});
                var it = std.mem.splitScalar(u8, e.text, '\n');
                while (it.next()) |line| {
                    if (it.index == null and line.len == 0) break;
                    try g.print("        \\\\{s}\n", .{line});
                }
                try g.put("        ,\n");
                e.deinit(g.a);
            }
            try g.put("    });\n");
        }
        // samplers by name, as their slots
        try g.put("    /// each sampler's texture unit\n    pub const samplers = struct {\n");
        for (r.samplers) |sm| try g.print("        pub const {f} = {d};\n", .{ std.zig.fmtId(sm.name), sm.slot });
        try g.put("    };\n");
        try g.put("    pub const info: Info = .{\n");
        try g.print("        .name = \"{s}\",\n", .{p.name});
        try g.put("        .vertex = vertex,\n        .fragment = fragment,\n");
        try g.put("        .blocks = &.{");
        for (r.blocks, 0..) |b, i| try g.print("{s}\"{s}\"", .{ if (i == 0) "" else ", ", b.name });
        try g.put("},\n        .samplers = &.{");
        for (r.samplers, 0..) |sm, i| try g.print("{s}\"{s}\"", .{ if (i == 0) "" else ", ", sm.name });
        try g.put("},\n        .uniforms = &.{\n");
        for (r.uniforms) |u| {
            try g.print("            .{{ .name = \"{s}\", .type = .{s}, .len = {d}, .meta = ", .{ u.name, glslType(g.s, u.type), arrayLen(g.s, u.type) });
            try g.metas(u.meta);
            try g.put(" },\n");
        }
        try g.put("        },\n        .params = &.{\n");
        for (r.params) |prm| {
            try g.print("            .{{ .name = \"{s}\", .type = .{s}, .default = &.{{", .{ prm.name, glslType(g.s, prm.type) });
            for (prm.default, 0..) |c, i| {
                try g.put(if (i == 0) " " else ", ");
                try g.number(c);
            }
            try g.put(" }, .meta = ");
            try g.metas(prm.meta);
            try g.put(" },\n");
        }
        try g.put("        },\n        .specs = &.{\n");
        for (r.specs) |sp| {
            try g.print("            .{{ .name = \"{s}\", .type = .{s}, .value = ", .{ sp.name, glslType(g.s, sp.type) });
            try g.number(sp.value);
            try g.put(", .default = ");
            try g.number(sp.default);
            try g.put(", .meta = ");
            try g.metas(sp.meta);
            try g.put(" },\n");
        }
        try g.put("        },\n        .inputs = &.{\n");
        for (r.inputs) |in| {
            try g.print("            .{{ .name = \"{s}\", .type = .{s}, .location = ", .{ in.name, glslType(g.s, in.type) });
            if (in.location) |l| try g.print("{d}", .{l}) else try g.put("null");
            try g.put(" },\n");
        }
        try g.put("        },\n        .files = &.{");
        for (r.files, 0..) |f, i| try g.print("{s}\"{f}\"", .{ if (i == 0) "" else ", ", std.zig.fmtString(f) });
        try g.put("},\n    };\n};\n");
    }

    fn metas(g: *Gen, ms: []const R.Meta) Error!void {
        try g.put("&.{");
        for (ms, 0..) |m, i| {
            try g.print("{s}.{{ .key = \"{s}\", .args = &.{{", .{ if (i == 0) " " else ", ", m.key });
            for (m.args, 0..) |arg, k| {
                try g.put(if (k == 0) " " else ", ");
                switch (arg) {
                    .value => |c| {
                        try g.put(".{ .number = ");
                        try g.number(c);
                        try g.put(" }");
                    },
                    .string => |str| try g.print(".{{ .string = \"{f}\" }}", .{std.zig.fmtString(str)}),
                    .word => |str| try g.print(".{{ .word = \"{f}\" }}", .{std.zig.fmtString(str)}),
                }
            }
            try g.put(" } }");
        }
        try g.put(if (ms.len > 0) " }" else "}");
    }

    /// A constant as an `f64` (every scalar of a param or spec fits one exactly).
    fn number(g: *Gen, c: Ir.Const) Error!void {
        switch (c) {
            .bool => |b| try g.put(if (b) "1" else "0"),
            .int => |i| try g.print("{d}", .{i}),
            .uint => |u| try g.print("{d}", .{u}),
            .float => |f| {
                var buf: [64]u8 = undefined;
                const d = std.fmt.bufPrint(&buf, "{d}", .{f}) catch unreachable;
                try g.put(d);
            },
        }
    }
};

fn scalarZig(s: types.Scalar) []const u8 {
    return switch (s) {
        .bool, .uint => "u32",
        .int => "i32",
        .float, .half => "f32",
    };
}

fn glslType(s: *const Session, t: Type) []const u8 {
    if (s.pool.arrayOf(t)) |a| return glslType(s, a.elem);
    if (s.pool.structOf(t) != null) return "@\"struct\"";
    return @tagName(t);
}

fn arrayLen(s: *const Session, t: Type) u32 {
    return if (s.pool.arrayOf(t)) |a| a.len else 0;
}

/// The types every generated file has.
const prelude =
    \\/// A GLSL type, as reflection names it.
    \\pub const Type = enum { @"bool", int, uint, float, half, bvec2, bvec3, bvec4, ivec2, ivec3, ivec4, uvec2, uvec3, uvec4, vec2, vec3, vec4, hvec2, hvec3, hvec4, mat2, mat3, mat4, hmat2, hmat3, hmat4, sampler2D, @"struct" };
    \\
    \\/// An argument of metadata: a number (bools are 0 and 1), a string, or a bare word.
    \\pub const Arg = union(enum) { number: f64, string: []const u8, word: []const u8 };
    \\
    \\/// `key(args)` from a declaration's `{ ... }`.
    \\pub const Meta = struct { key: []const u8, args: []const Arg };
    \\
    \\pub const Uniform = struct { name: []const u8, type: Type, len: u32, meta: []const Meta };
    \\pub const Param = struct { name: []const u8, type: Type, default: []const f64, meta: []const Meta };
    \\pub const Spec = struct { name: []const u8, type: Type, value: f64, default: f64, meta: []const Meta };
    \\pub const Input = struct { name: []const u8, type: Type, location: ?u32 };
    \\
    \\/// A program: its texts, and what a host binds to run it.
    \\pub const Info = struct {
    \\    name: []const u8,
    \\    vertex: Texts,
    \\    fragment: Texts,
    \\    /// the uniform blocks it uses (in `blocks`)
    \\    blocks: []const []const u8,
    \\    /// its samplers, in slot order
    \\    samplers: []const []const u8,
    \\    uniforms: []const Uniform,
    \\    params: []const Param,
    \\    specs: []const Spec,
    \\    inputs: []const Input,
    \\    /// the sources it was made from
    \\    files: []const []const u8,
    \\};
    \\
;
